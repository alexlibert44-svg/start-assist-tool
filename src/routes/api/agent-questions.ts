import { createFileRoute } from "@tanstack/react-router";
import { z } from "zod";
import { requireUserId } from "@/server/auth.server";
import { generateQuestions, readWorkflow, writeWorkflow, QuestionError } from "@/server/agent-questions.server";
import { WORKFLOWS, workflowStateSchema } from "@/shared/agent-questions";
import { ONBOARDING_QUESTIONS } from "@/shared/onboarding-questions";
import { FIELDS } from "@/shared/question-fields";
import { questionSchema } from "@/shared/agent-questions";

const input = z.object({ workflow: z.enum(WORKFLOWS), key: z.string().min(1).max(50), answers: z.record(z.unknown()).default({}), resume: z.boolean().default(false) });
export const Route = createFileRoute("/api/agent-questions")({ server: { handlers: {
  GET: async ({ request }) => {
    const uid = await requireUserId(request);
    const workflow = z.enum(WORKFLOWS).parse(new URL(request.url).searchParams.get("workflow"));
    return Response.json(await readWorkflow(uid, workflow), { headers: { "Cache-Control": "no-store" } });
  },
  POST: async ({ request }) => {
    const uid = await requireUserId(request);
    try {
      const body = input.parse(await request.json());
      if (body.workflow === "onboarding") return Response.json({ message: "Initial questions are provided by the application." }, { status: 400 });
      if (body.workflow === "planning") return Response.json({ message: "Planning questions are generated by Larry's conversation." }, { status: 400 });
      const old = await readWorkflow(uid, body.workflow);
      const existing = old?.questions.find((q) => q.key === body.key);
      const field = FIELDS[body.workflow].find((f) => f.key === body.key);
      const predefined = field ? questionSchema.parse({ ...field, options: field.options ?? [], optional: !!field.optional, custom: !!field.custom }) : undefined;
      if (existing && JSON.stringify(existing) !== JSON.stringify(predefined)) return Response.json(existing);
      const questions = await generateQuestions(uid, body.workflow, body.key, body.answers, request.signal, body.resume);
      const state = { questions: [...(old?.questions ?? []).filter((q) => !questions.some((generated) => generated.key === q.key)), ...questions], answers: old?.answers ?? {}, step: old?.step ?? 0 };
      await writeWorkflow(uid, body.workflow, workflowStateSchema.parse(state));
      return Response.json(questions[0]);
    } catch (e) {
      console.error("Agent question failure", e);
      if (e instanceof z.ZodError) return Response.json({ message: "Invalid question request." }, { status: 400 });
      return Response.json({ message: e instanceof QuestionError ? e.message : "Could not prepare the question. Your answers are kept." }, { status: e instanceof QuestionError ? e.status : 500 });
    }
  },
  PUT: async ({ request }) => {
    const uid = await requireUserId(request);
    try {
      const { workflow, state } = z.object({ workflow: z.enum(WORKFLOWS), state: workflowStateSchema }).parse(await request.json());
      const existing = await readWorkflow(uid, workflow);
      const base = workflow === "onboarding" ? ONBOARDING_QUESTIONS : workflow === "planning" ? [] : FIELDS[workflow].map((f) => questionSchema.parse({ ...f, options: f.options ?? [], optional: !!f.optional, custom: !!f.custom }));
      // Definitions come only from trusted application configuration or previously validated AI output.
      const definitions = workflow === "onboarding" ? base : base.map((q) => existing?.questions.find((saved) => saved.key === q.key) ?? q);
      return Response.json(await writeWorkflow(uid, workflow, { ...state, questions: definitions.length ? definitions : existing?.questions ?? [] }));
    } catch { return Response.json({ message: "Could not save your answers. Please try again." }, { status: 400 }); }
  },
} } });